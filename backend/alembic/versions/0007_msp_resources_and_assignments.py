"""msp resources and assignments

Core's MSP tables record what was scheduled and how far along each task is. They record
nothing about *what* a task consumes: no resource, no unit, no quantity. So a Finance line
that says "1,329,121 kg of rebar" has never had anything on the Core side to compare itself
against, and every quantity in the progress feed has come back null.

These two tables close that gap. `msp_resources` is the Resource Sheet -- one row per
resource per snapshot -- and `msp_resource_assignments` is the task-by-resource grid
underneath it, which is where the quantity that a WBS rollup can actually use lives.

OWNERSHIP
This revision creates two tables named for Core's MSP domain. That is a deliberate decision
by the project owner: this Alembic chain manages the Finance schema *and* these two tables.
Existing Core tables -- `msp_snapshots`, `msp_tasks`, `msp_file_versions` -- are not
created, not altered, not referenced and not read for data here.

WHY THERE IS NO FOREIGN KEY INTO CORE
The production migration role has no REFERENCES privilege on Core tables, and there is no
administrator account available to grant one. A revision that declared those keys would
simply fail to apply. So `snapshot_id` and `task_uid` are ordinary columns, and the three
relationships below are LOGICAL -- upheld by the importer and checked by SQL, not by the
database:

    msp_resources.snapshot_id             -> msp_snapshots.id
    msp_resource_assignments.snapshot_id  -> msp_snapshots.id
    msp_resource_assignments.task_uid     -> msp_tasks.uid, within the same snapshot

WHAT THAT COSTS, SAID PLAINLY
A foreign key would have carried ON DELETE CASCADE, and Core does delete snapshots -- they
cascade from `projects`. Without it, deleting a project in Core leaves this table's rows
behind, pointing at a snapshot that no longer exists. Nothing breaks loudly; the rows simply
become unreachable clutter that still answers COUNT(*).

Two things stand in for the missing key, and both are deliberate:

  * the importer must verify the snapshot exists and the task belongs to it BEFORE
    publishing a feed, and fail the whole import if not -- see
    docs/MSP_PARSER_RESOURCE_ASSIGNMENT_IMPLEMENTATION_SPEC.md;
  * docs/sql/msp_resource_assignment_data_validation.sql counts orphans explicitly, so they
    are found by looking rather than by someone noticing a wrong total.

`msp_tasks` could not have been referenced in any case: it has `PRIMARY KEY (id)` and no
`UNIQUE (snapshot_id, uid)` for a composite key to point at.

WHAT THE NUMBERS MEAN
`resource_quantity` and `planned_quantity` are physical -- kilograms, cubic metres -- read
from MPXJ's Material field. `work` is hours. They are separate columns because Finance's
progress precedence prefers a physical quantity and treats work as a weaker fallback, and
that only works if the two can never arrive in the same place.

`standard_rate`, `source_cost` and `source_actual_cost` are reference only. The
authoritative price is `price_versions` and the authoritative actual cost is a confirmed
invoice; a rate typed into a Resource Sheet is neither.

IDENTITY, AND WHY GUID IS NOT IT
Two saved versions of one real schedule were compared: 1248 of 1248 task UIDs survived and
0 of 1248 GUIDs did -- saving the file under a new name regenerates every GUID while
changing nothing else. So `resource_uid` and `assignment_uid` are the identity, GUID is
kept only for diagnosis, and no cross-snapshot uniqueness is asserted anywhere. If UIDs
ever do move between versions, the result is rows that fail to match -- visible -- rather
than rows silently joined to the wrong thing.

The DDL below is the same statement tested in
`docs/sql/msp_resource_assignment_apply.sql`, which remains as the operational package for
anyone applying this outside Alembic.
"""

from alembic import op
from sqlalchemy import DDL

