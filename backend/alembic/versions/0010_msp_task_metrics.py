UPGRADE_SQL = r"""
DO $precheck$
BEGIN
    IF to_regclass('msp_snapshots') IS NULL OR to_regclass('msp_tasks') IS NULL THEN
        RAISE EXCEPTION USING
            ERRCODE = '42P01',
            MESSAGE = '0010 requires the Core tables msp_snapshots and msp_tasks to '
                      'exist: msp_task_metrics is logically keyed to them. Create the '
                      'Core schema first, or do not run this revision here.';
    END IF;
END
$precheck$;

CREATE TABLE msp_task_metrics (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id bigint NOT NULL,
    task_uid integer NOT NULL,

    -- Physical quantities of the work item (آحجام / احجام).
    item_quantity numeric,
    item_quantity_text text,
    work_volume numeric,
    done_volume numeric,
    initial_volume numeric,
    work_volume_percent numeric,

    -- Weighting coefficients the rollup is built on.
    weight_time numeric,
    weight_rial numeric,
    weight_base numeric,
    weight_percent numeric,
    wf_time numeric,
    wf_rial numeric,
    wf_physical numeric,

    -- Progress measures the planners maintain beside the standard percentage.
    actual_progress numeric,
    actual_progress_percent numeric,
    physical_progress numeric,
    planned_progress numeric,
    planned_progress_component numeric,
    progress_variance numeric,

    -- The planners' own Jalali dates, kept as text: converting a calendar we have not
    -- confirmed would invent data.
    jalali_start text,
    jalali_finish text,

    -- The task's own cost, as the file states it. Finance still prices its lines itself;
    -- this is the schedule's number, recorded for comparison, never Finance's official one.
    task_cost numeric,
    task_actual_cost numeric,
    task_fixed_cost numeric,

    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (snapshot_id, task_uid)
);

COMMENT ON TABLE msp_task_metrics IS
    'One row per task per snapshot: the custom Task columns of an MPP schedule, read by '
    'the planner''s alias and owned by Core. Logically keyed to msp_snapshots.id and '
    'msp_tasks.uid; no FK, matching msp_resource_assignments.';
COMMENT ON COLUMN msp_task_metrics.task_uid IS
    'msp_tasks.uid within this snapshot -- the stable MSP identity, not the display ID.';

CREATE INDEX ix_msp_task_metrics_snapshot ON msp_task_metrics (snapshot_id);
"""


DOWNGRADE_SQL = r"""
DROP TABLE IF EXISTS msp_task_metrics;
"""


