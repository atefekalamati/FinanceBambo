"""per-task schedule metrics that the finance side reads

Revision ID: 0010
Revises: 0009

A construction schedule in this shop carries far more on each task than dates and a
percentage. The planners keep, in custom Task columns, the physical quantity of the work
item, three weighting coefficients (rial, time, base), several progress measures (actual,
physical, planned) and the task's own cost. Those columns are what a finance rollup is
actually built on, and until now the importer read none of them.

They are TASK-level fields and Core owns them, so they live in a Core table, NOT in
Finance. `msp_task_metrics` is that table -- one row per task per snapshot, created by
this chain exactly as revision 0007 created `msp_resources` and
`msp_resource_assignments`.

WHY THE VALUES ARE READ BY ALIAS, NOT BY COLUMN INDEX
The planner named each column ("ضریب وزنی ریالی"); MS Project stored it in whatever
`NumberN` slot was free. The slot is not stable between files, the name is -- so the
reader maps by alias and this table's columns are named for the MEANING, never for a
`NumberN`.

WHY THERE IS NO FOREIGN KEY INTO CORE
Same reason 0007 gave for its two tables, and the same invariant 0009 pinned: exactly one
sanctioned key reaches into Core (`finance_task_resource_map.task_id`). This table keeps
the logical link `msp_resource_assignments` uses -- `snapshot_id` -> `msp_snapshots.id`
and `task_uid` -> `msp_tasks.uid` within that snapshot -- upheld by the importer, not by a
database constraint.

WHAT IS NOT HERE
No resource quantity (that is `msp_resources.resource_quantity`), no assignment quantity
(that is `msp_resource_assignments.*_quantity`), and nothing Finance computes for itself.
There are no value CHECK constraints: this table records what the file states, and a
schedule may legitimately carry a negative progress variance -- a check that rejected it
would turn a valid file into a failed import. The complete raw column set the file
carries, including columns nobody has mapped yet, is preserved separately in
`msp_tasks.raw_fields_json`.
"""

from alembic import op
from sqlalchemy import DDL


revision = "0010"
down_revision = "0009"
branch_labels = None
